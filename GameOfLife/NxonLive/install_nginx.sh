#!/usr/bin/env bash
# install_nginx.sh — auto-configure nginx as a TLS terminator + WS-aware
# reverse proxy in front of mngol5. Reads the domain from
# world_config.json ("canonical_host") so you don't edit nginx by hand.
#
# Run AFTER:
#   sudo certbot certonly --nginx -d your.domain      # or --standalone
# (certbot deploys a basic site config; this script REPLACES it with a
# WebSocket-correct one and points it at the mngol5 backend.)
#
# Usage:   sudo ./install_nginx.sh [config-path] [backend-port]
# Default: ./world_config.json   8443
# ===================================================================
set -euo pipefail

CONFIG="${1:-$(dirname "$0")/world_config.json}"
PORT="${2:-8443}"

if [ "$EUID" -ne 0 ]; then
    echo "Run as root:  sudo $0 [config-path] [backend-port]" >&2
    exit 1
fi
if [ ! -f "$CONFIG" ]; then
    echo "Config not found: $CONFIG" >&2
    exit 1
fi
if ! command -v nginx >/dev/null 2>&1; then
    echo "nginx not installed.  sudo apt install nginx" >&2
    exit 1
fi

# Read canonical_host from the JSON config (no jq dependency)
HOST="$(python3 -c "
import json,sys
c=json.load(open('$CONFIG'))
print((c.get('canonical_host') or '').strip())")"
if [ -z "$HOST" ]; then
    cat >&2 <<EOF
"canonical_host" is empty in $CONFIG.
Set it first, e.g.:
    "canonical_host": "nxon.online",
    "force_https":    true,
then re-run this script.
EOF
    exit 1
fi

CERT="/etc/letsencrypt/live/$HOST/fullchain.pem"
KEY="/etc/letsencrypt/live/$HOST/privkey.pem"
if [ ! -f "$CERT" ] || [ ! -f "$KEY" ]; then
    cat >&2 <<EOF
No Let's Encrypt certificate for $HOST.
Get one first (port 80 must reach this server and DNS must already
point at it):
    sudo certbot certonly --nginx -d $HOST
or, if nginx isn't running yet:
    sudo certbot certonly --standalone -d $HOST
EOF
    exit 1
fi

SITE=/etc/nginx/sites-available/mngol5
echo "[install_nginx] writing $SITE  (host=$HOST  backend=127.0.0.1:$PORT)"

cat > "$SITE" <<NGINX_EOF
# Auto-generated by mngol5/install_nginx.sh  — do not edit by hand;
# re-run the script when world_config.json changes.

# Map: Connection header is "upgrade" ONLY for real WebSocket
# requests; for normal HTTP it must be "close". Hardcoding
# \"Connection: upgrade\" on every request (the old config) made the
# browser hang waiting for a WebSocket upgrade on plain GETs like
# /api/world — which left the client stuck on the loading screen,
# especially for large worlds whose /api/world JSON is hundreds of KB.
map \$http_upgrade \$mngol5_conn {
    default upgrade;
    ''      close;
}

# Port 80: redirect everything to HTTPS.
server {
    listen 80;
    listen [::]:80;
    server_name $HOST;

    # Let's Encrypt HTTP-01 renewal challenges land here. Keep this
    # location BEFORE the catch-all redirect so renewals keep working.
    location /.well-known/acme-challenge/ {
        root /var/www/html;
    }

    location / {
        return 308 https://\$host\$request_uri;
    }
}

# TLS terminator -> mngol5 backend on localhost.
server {
    listen      443 ssl http2;
    listen [::]:443 ssl http2;
    server_name $HOST;

    ssl_certificate     $CERT;
    ssl_certificate_key $KEY;
    include             /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam         /etc/letsencrypt/ssl-dhparams.pem;

    # mngol5 traffic is tiny JSON snapshots; no large uploads.
    client_max_body_size 4m;

    # WebSocket endpoint — keep it open as long as the tab is open
    # (default 60s read timeout would kill the live stream) and
    # disable buffering so frames flow immediately.
    location /ws {
        proxy_pass http://127.0.0.1:$PORT;
        proxy_http_version 1.1;
        proxy_set_header   Upgrade           \$http_upgrade;
        proxy_set_header   Connection        \$mngol5_conn;
        proxy_set_header   Host              \$host;
        proxy_set_header   X-Real-IP         \$remote_addr;
        proxy_set_header   X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header   X-Forwarded-Proto \$scheme;
        proxy_read_timeout 86400;
        proxy_send_timeout 86400;
        proxy_buffering    off;
    }

    # Everything else: ordinary HTTP reverse proxy. Buffering ON so
    # large JSON responses (e.g. /api/world for big worlds) are
    # delivered cleanly, and NO forced Upgrade header.
    location / {
        proxy_pass http://127.0.0.1:$PORT;
        proxy_http_version 1.1;
        proxy_set_header   Connection        \$mngol5_conn;
        proxy_set_header   Upgrade           \$http_upgrade;
        proxy_set_header   Host              \$host;
        proxy_set_header   X-Real-IP         \$remote_addr;
        proxy_set_header   X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header   X-Forwarded-Proto \$scheme;
    }
}
NGINX_EOF

# Enable our site, disable the certbot-generated default if present.
ln -sfn "$SITE" /etc/nginx/sites-enabled/mngol5
if [ -e /etc/nginx/sites-enabled/default ]; then
    echo "[install_nginx] disabling /etc/nginx/sites-enabled/default"
    rm -f /etc/nginx/sites-enabled/default
fi

# Test config before reloading so a typo can't take the site down.
nginx -t
systemctl reload nginx

cat <<EOF

[install_nginx] OK.
  https://$HOST  ->  http://127.0.0.1:$PORT  (mngol5)
  http://$HOST   ->  308 redirect to https

Make sure:
  * mngol5 binds to 127.0.0.1 (run_server.sh does this automatically
    when canonical_host is set in world_config.json).
  * In world_config.json:  "force_https": true.
  * Firewall: allow 80,443/tcp publicly; block $PORT from outside.
      sudo ufw allow 80,443/tcp
      sudo ufw deny $PORT/tcp
EOF
